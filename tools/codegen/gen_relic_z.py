#!/usr/bin/env python3
"""Emit cairn_relic_z.hpp: the world Z (height) of each kEffigies entry.

kEffigies (cairn_data.hpp) is GUID + x,y only. The compass wants to show whether
an effigy is above or below the player, which needs Z. Every effigy is a
BP_LevelObject_Relic*_C actor in ONE World Partition cell of Pal-Windows.pak
(Pal/Content/Pal/Maps/MainWorld_5/PL_MainWorld5/_Generated_/
MainGrid_L15_X0_Y0_DL961A8730) -- World Tree effigies included, no level-instance
offset. Its position is the first FVector (3 x f64) of the actor's
DefaultSceneRoot SceneComponent; its FGuid is the 16 bytes right after the int32
reference to that root export in the actor's body. data/codegen/relic_z.json holds
that offline extraction: {GUID: {z, x, y, class}}.

This script joins relic_z.json onto relic_guids.json BY GUID and emits an int32_t
array PARALLEL to kEffigies, in the same order. A kEffigies GUID that is not in
relic_z.json gets INT32_MIN (no Z known -- caller must not show above/below).
It also checks that relic_guids.json is in kEffigies order (cairn_data.hpp).

Standalone, additive header -- like gen_relic_types.py, kept out of
gen_cairn_data.py / verify_parity. Re-run whenever relic_guids.json or
relic_z.json changes:

    python3 tools/codegen/gen_relic_z.py [--check]

--check regenerates in memory and compares to the committed header (for CI).
"""

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
RELIC_GUIDS = REPO / "data/codegen/relic_guids.json"
RELIC_Z = REPO / "data/codegen/relic_z.json"
CAIRN_DATA = REPO / "cpp-mod/mods/CairnMap/src/cairn_data.hpp"
OUT = REPO / "cpp-mod/mods/CairnMap/src/cairn_relic_z.hpp"

INT32_MIN = -(2 ** 31)
EFFIGIES_RE = re.compile(r"inline\s+constexpr\s+GuidPoint\s+kEffigies\s*\[\]\s*=\s*\{(.*?)\};", re.S)
GUID_RE = re.compile(r"\{\s*0[xX]([0-9a-fA-F]{8})\s*,\s*0[xX]([0-9a-fA-F]{8})\s*,"
                     r"\s*0[xX]([0-9a-fA-F]{8})\s*,\s*0[xX]([0-9a-fA-F]{8})\s*\}")


def header_order():
    m = EFFIGIES_RE.search(CAIRN_DATA.read_text(encoding="utf-8"))
    if not m:
        sys.exit(f"error: kEffigies not found in {CAIRN_DATA}")
    return ["".join(g).upper() for g in GUID_RE.findall(m[1])]


def build():
    relic = json.loads(RELIC_GUIDS.read_text())["Relic"]
    zs = json.loads(RELIC_Z.read_text())
    guids = [row[0] for row in relic]
    if guids != header_order():
        sys.exit(f"error: {RELIC_GUIDS.name} order/count differs from kEffigies in "
                 f"{CAIRN_DATA.name} -- re-run freeze_inputs.py")
    seq, missing = [], []
    for guid in guids:
        if guid in zs:
            seq.append(int(zs[guid]["z"]))
        else:
            seq.append(INT32_MIN)
            missing.append(guid)

    body = ",".join("INT32_MIN" if z == INT32_MIN else str(z) for z in seq)
    lines = [
        "// Generated by tools/codegen/gen_relic_z.py - DO NOT EDIT",
        "// World Z (Unreal units) per kEffigies entry, SAME order as kEffigies",
        "// (data/codegen/relic_guids.json \"Relic\"), from data/codegen/relic_z.json.",
        "// INT32_MIN = no Z known for that effigy (GUID not found in the pak):",
        "// treat as unknown, do not show above/below.",
        "#pragma once",
        "#include <cstdint>",
        "#include <cstddef>",
        "",
        "namespace CairnMap::Data {",
        f"inline constexpr int32_t kEffigyZ[] = {{{body}}};",
        f"inline constexpr size_t kEffigyZCount = {len(seq)};",
        "} // namespace CairnMap::Data",
        "",
    ]
    return "\n".join(lines), len(seq), missing


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="compare to the committed header instead of writing")
    args = ap.parse_args()
    text, n, missing = build()
    for g in missing:
        print(f"  warning: no Z for effigy {g} -> INT32_MIN")
    if args.check:
        if not OUT.exists():
            sys.exit(f"MISSING {OUT}")
        if OUT.read_text() != text:
            sys.exit(f"DRIFT {OUT} no longer matches relic_guids.json + relic_z.json")
        print(f"  ok      cairn_relic_z.hpp {n} effigy Z ({len(missing)} unknown)")
    else:
        OUT.write_text(text)
        print(f"  wrote   {n} effigy Z ({len(missing)} unknown) -> {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
